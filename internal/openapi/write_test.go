func TestWrite_WritesAMockFileThatNamesItsSpec(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "mocks")

	report, err := openapi.Write(dir, "Pets", []openapi.File{{Name: "pets.get.200.json.mock.yaml", Mocks: []openapi.Mock{{
		ID: "pets.get.200.json", Name: "List pets", Priority: 300, Enabled: true,
		Request: openapi.Request{Method: "GET", Path: "/pets", Accept: []any{"accept", "application/json", []any{"application/json"}}},
		Reply:   openapi.Reply{Status: 200, Header: map[string]string{"Content-Type": "application/json"}, Body: []any{map[string]any{"id": 1}}},
	}}}})
	require.NoError(t, err)
	require.Equal(t, &openapi.Report{Written: []string{"pets.get.200.json.mock.yaml"}}, report)

	data, err := os.ReadFile(filepath.Join(dir, "pets.get.200.json.mock.yaml"))
	require.NoError(t, err)
	require.Equal(t, `# Code generated by vlatte openapi from "Pets". DO NOT EDIT.
enabled: true
id: pets.get.200.json
name: List pets
priority: 300
request:
    headers:
        Accept:
            - accept
            - application/json
            - - application/json
    method: GET
    path: /pets
response:
    body:
        - id: 1
    header:
        Content-Type: application/json
    status: 200
`, string(data))
}

func TestWrite_WritesEachMockOfAFileAsADocument(t *testing.T) {
	dir := t.TempDir()

	_, err := openapi.Write(dir, "Pets", []openapi.File{{Name: "pets.mock.yaml", Mocks: []openapi.Mock{
		{ID: "a", Request: openapi.Request{Method: "GET", PathTemplate: "/a/{id}"}, Reply: openapi.Reply{Status: 204}},
		{ID: "b", Request: openapi.Request{Method: "GET", Path: []any{"regex", "^/b$"}}, Reply: openapi.Reply{Status: 200, Body: "b"}},
	}}})
	require.NoError(t, err)

	data, err := os.ReadFile(filepath.Join(dir, "pets.mock.yaml"))
	require.NoError(t, err)
	require.Equal(t, `# Code generated by vlatte openapi from "Pets". DO NOT EDIT.
enabled: false
id: a
name: ""
priority: 0
request:
    method: GET
    path_template: /a/{id}
response:
    status: 204
---
enabled: false
id: b
name: ""
priority: 0
request:
    method: GET
    path:
        - regex
        - ^/b$
response:
    body: b
    status: 200
`, string(data))
}

func TestWrite_ARerunOverwritesItsOwnFilesAndListsTheStaleOnes(t *testing.T) {
	// The spec may drop an operation: its file still loads and answers, so the rerun says so, but deleting it is
	// the user's call.
	dir := t.TempDir()
	file := func(name string) openapi.File {
		return openapi.File{Name: name, Mocks: []openapi.Mock{{ID: name, Request: openapi.Request{Method: "GET", Path: "/"}, Reply: openapi.Reply{Status: 200}}}}
	}

	_, err := openapi.Write(dir, "Pets", []openapi.File{file("a.mock.yaml"), file("b.mock.yaml")})
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(filepath.Join(dir, "mine.mock.yaml"), []byte("id: mine\n"), 0o600))

	report, err := openapi.Write(dir, "Pets", []openapi.File{file("a.mock.yaml")})
	require.NoError(t, err)
	require.Equal(t, &openapi.Report{Written: []string{"a.mock.yaml"}, Stale: []string{"b.mock.yaml"}}, report)
	require.FileExists(t, filepath.Join(dir, "b.mock.yaml"))
}

func TestWrite_KnowsItsFilesWithWindowsLineEndings(t *testing.T) {
	// Git with core.autocrlf checks generated files out with CRLF: they are still the generator's to rewrite.
	dir := t.TempDir()
	file := func(name string) openapi.File {
		return openapi.File{Name: name, Mocks: []openapi.Mock{{ID: name, Request: openapi.Request{Method: "GET", Path: "/"}, Reply: openapi.Reply{Status: 200}}}}
	}

	_, err := openapi.Write(dir, "Pets", []openapi.File{file("a.mock.yaml"), file("b.mock.yaml")})
	require.NoError(t, err)

	for _, name := range []string{"a.mock.yaml", "b.mock.yaml"} {
		path := filepath.Join(dir, name)
		data, err := os.ReadFile(path)
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(path, bytes.ReplaceAll(data, []byte("\n"), []byte("\r\n")), 0o600))
	}

	report, err := openapi.Write(dir, "Pets", []openapi.File{file("a.mock.yaml")})
	require.NoError(t, err)
	require.Equal(t, &openapi.Report{Written: []string{"a.mock.yaml"}, Stale: []string{"b.mock.yaml"}}, report)
}

func TestWrite_NeverOverwritesAFileItDidNotWriteFromTheSpec(t *testing.T) {
	// A mock written by hand, or generated from another spec into the same folder, is someone else's work.
	dir := t.TempDir()
	mine := filepath.Join(dir, "a.mock.yaml")
	require.NoError(t, os.WriteFile(mine, []byte("id: mine\n"), 0o600))

	_, err := openapi.Write(dir, "Other", []openapi.File{{Name: "c.mock.yaml", Mocks: []openapi.Mock{{ID: "c", Reply: openapi.Reply{Status: 200}}}}})
	require.NoError(t, err)

	files := []openapi.File{
		{Name: "a.mock.yaml", Mocks: []openapi.Mock{{ID: "a", Reply: openapi.Reply{Status: 200}}}},
		{Name: "b.mock.yaml", Mocks: []openapi.Mock{{ID: "b", Reply: openapi.Reply{Status: 200}}}},
		{Name: "c.mock.yaml", Mocks: []openapi.Mock{{ID: "c", Reply: openapi.Reply{Status: 200}}}},
	}

	_, err = openapi.Write(dir, "Pets", files)
	require.ErrorIs(t, err, openapi.ErrNotGenerated)
	require.EqualError(t, err, "openapi: a file to write is not one generated from this spec: a.mock.yaml, c.mock.yaml: move them, or write to another folder")

	data, err := os.ReadFile(mine)
	require.NoError(t, err)
	require.Equal(t, "id: mine\n", string(data))
	require.NoFileExists(t, filepath.Join(dir, "b.mock.yaml"))
}
