package openapi

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/caffeine-projects/vlatte/internal/atomicfile"
	"github.com/caffeine-projects/vlatte/internal/config"
	"github.com/caffeine-projects/vlatte/internal/value"
)

// _marker starts the first line of every file [Write] writes.
const _marker = "# Code generated by vlatte openapi"

// _tempPattern names the files being written: never *.mock.*, so loading mock files skips them.
const _tempPattern = ".openapi-*.tmp"

// Report is what [Write] did.
type Report struct {
	// Written are the names of the files it wrote.
	Written []string

	// Stale are the names of the files generated from the same spec before that it no longer writes, which still
	// load: the spec may have dropped their operation.
	Stale []string
}

// Write writes files to dir, which it creates if missing. Each file's first line says it was generated from the spec
// titled title, so a rerun overwrites the files it wrote, and lists those it no longer writes as stale, deleting
// none. When a file to write exists and wasn't generated from that spec, such as a mock written by hand or generated
// from another spec, it writes nothing, and fails with [ErrNotGenerated] naming each one.
func Write(dir, title string, files []File) (*Report, error) {
	header := fmt.Sprintf("%s from %s. DO NOT EDIT.\n", _marker, strconv.Quote(title))

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("openapi: creating %s: %w", dir, err)
	}

	contents := make([][]byte, len(files))

	var conflicts []string

	for i, f := range files {
		data, err := encodeFile(header, f)
		if err != nil {
			return nil, fmt.Errorf("openapi: writing %s: %w", f.Name, err)
		}

		contents[i] = data

		first, err := firstLine(filepath.Join(dir, f.Name))
		switch {
		case errors.Is(err, fs.ErrNotExist):
		case err != nil:
			return nil, fmt.Errorf("openapi: reading %s: %w", f.Name, err)
		case first != header:
			conflicts = append(conflicts, f.Name)
		}
	}

	if len(conflicts) > 0 {
		return nil, fmt.Errorf("%w: %s: move them, or write to another folder", ErrNotGenerated, strings.Join(conflicts, ", "))
	}

	report := &Report{}

	for i, f := range files {
		if err := atomicfile.Write(dir, _tempPattern, filepath.Join(dir, f.Name), contents[i]); err != nil {
			return report, fmt.Errorf("openapi: writing %s: %w", f.Name, err)
		}

		report.Written = append(report.Written, f.Name)
	}

	report.Stale = staleFiles(dir, header, report.Written)

	return report, nil
}

// encodeFile returns the content of f: header, then a YAML document for each of its mocks.
func encodeFile(header string, f File) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString(header)

	for i, m := range f.Mocks {
		if i > 0 {
			b.WriteString("---\n")
		}

		doc, err := value.ViaJSON(mockDoc(m))
		if err != nil {
			return nil, err
		}

		// doc went through JSON: YAML holds it.
		data, _ := config.Encode(doc, "yaml")
		b.Write(data)
	}

	return b.Bytes(), nil
}

// mockDoc returns m as a mock file document.
func mockDoc(m Mock) map[string]any {
	req := map[string]any{"method": m.Request.Method}

	if m.Request.Path != nil {
		req["path"] = m.Request.Path
	} else {
		req["path_template"] = m.Request.PathTemplate
	}

	if m.Request.Accept != nil {
		req["headers"] = map[string]any{"Accept": m.Request.Accept}
	}

	res := map[string]any{"status": m.Reply.Status}
	if len(m.Reply.Header) > 0 {
		res["header"] = m.Reply.Header
	}

	if m.Reply.Body != nil {
		res["body"] = m.Reply.Body
	}

	return map[string]any{
		"id":       m.ID,
		"name":     m.Name,
		"priority": m.Priority,
		"enabled":  m.Enabled,
		"request":  req,
		"response": res,
	}
}

// firstLine returns the first line of the file at path, with its line break, a CRLF read as LF.
func firstLine(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}

	line, _, _ := bytes.Cut(data, []byte("\n"))

	return string(bytes.TrimSuffix(line, []byte("\r"))) + "\n", nil
}

// staleFiles returns the names of the files of dir whose first line is header, but written. Write just wrote to dir:
// a listing that fails there lists what it read.
func staleFiles(dir, header string, written []string) []string {
	entries, _ := os.ReadDir(dir)

	var stale []string

	for _, e := range entries {
		if !e.Type().IsRegular() || slices.Contains(written, e.Name()) {
			continue
		}

		if first, err := firstLine(filepath.Join(dir, e.Name())); err == nil && first == header {
			stale = append(stale, e.Name())
		}
	}

	return stale
}
